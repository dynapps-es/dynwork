// The admin login offers only Microsoft Entra, and the local Entra secret is a dummy. The core OAuth authorize page
// signs in with a passkey instead: the CLI issues a passkey setup link for the user, a virtual authenticator registers
// one, and a dynamically registered public client gets a JWT for the user through authorization code and PKCE.
// A passkey for userEmail on both hosts of the instance, from a setup link the CLI issues, held by a virtual authenticator.
async function registerPasskeys(run: Run) {
  const link = new URL(
    JSON.parse(
      await cli(run.instance, "admin", "users", "webauthn", "generate-setup-token", "--email", userEmail, "--expires-minutes", "5", "--json"),
    ).content,
  )
  const setupToken = keepSecret(run, link.searchParams.get("token") ?? "")
  const cdp = await run.context.newCDPSession(run.page)
  await cdp.send("WebAuthn.enable")
  await cdp.send("WebAuthn.addVirtualAuthenticator", {
    options: {
      protocol: "ctap2",
      transport: "internal",
      hasResidentKey: true,
      hasUserVerification: true,
      isUserVerified: true,
      automaticPresenceSimulation: true,
    },
  })
  const registerPasskey = async (origin: string) => {
    await Promise.all([
      run.page.waitForResponse((response) => response.url().includes("/webauthn/link/start")),
      run.page.goto(`${origin}/auth/link-passkey?token=${setupToken}`),
    ])
    await run.page.locator("#register-btn").click()
    const outcome = run.page.getByText(/registered successfully|invalid domain/i).first()
    await outcome.waitFor()
    return scrubText(await outcome.innerText(), run.scope)
  }
  const onAddress = await registerPasskey(run.api)
  const onLocalhost = await registerPasskey(run.web)
  return { link, onAddress, onLocalhost }
}

async function developmentLogin(run: Run) {
  run.section = "development-login"
  const passkeys = await registerPasskeys(run)

  const redirect = `http://127.0.0.1:${run.scope.port}/oauth`
  const registered = await fetch(`${run.api}/api/v1/core/oauth/register`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({
      client_name: captureLabel,
      redirect_uris: [redirect],
      token_endpoint_auth_method: "none",
      grant_types: ["authorization_code"],
      response_types: ["code"],
    }),
  })
  const client: unknown = await registered.json()
  const clientId = stringField(client, "client_id")
  keepSecret(run, stringField(client, "registration_access_token"))
  const verifier = randomBytes(32).toString("base64url")
  const state = randomBytes(16).toString("hex")
  const query = new URLSearchParams({
    response_type: "code",
    client_id: clientId,
    redirect_uri: redirect,
    scope: "user",
    state,
    code_challenge: createHash("sha256").update(verifier).digest("base64url"),
    code_challenge_method: "S256",
  })
  // The previous round ended on a redirect the browser could not open; start from a clean page.
  await run.page.goto("about:blank")
  await run.page.goto(`${run.web}/api/v1/core/oauth/authorize?${query}`)
  await run.page.locator("#email").fill(userEmail)
  await run.page.locator("#sign-in-btn").click()
  await run.page.locator("#authorize-btn").click()
  const hit = await takeHit(run.hits, "/oauth")
  const cookies = (await run.context.cookies(run.web)).map((cookie) => cookie.name)
  const token = await fetch(`${run.api}/api/v1/core/oauth/token`, {
    method: "POST",
    body: new URLSearchParams({
      grant_type: "authorization_code",
      code: keepSecret(run, hit.url.searchParams.get("code") ?? ""),
      redirect_uri: redirect,
      client_id: clientId,
      code_verifier: verifier,
    }),
  })
  const issued: unknown = await token.json()
  const jwt = keepSecret(run, stringField(issued, "access_token"))
  keepSecret(run, stringField(issued, "refresh_token"))
  const claims: unknown = JSON.parse(Buffer.from(jwt.split(".")[1] ?? "", "base64url").toString() || "{}")
  console.log(`  development login: passkey on 127.0.0.1 "${passkeys.onAddress}", on localhost "${passkeys.onLocalhost}"`)
  console.log(`  OAuth ${token.status}: JWT ${truncate(jwt)} for ${userEmail}, cookies after sign-in: ${cookies.length}`)
  return {
    jwt,
    record: {
      admin_login: "unavailable: Microsoft Entra only, and the local instance has a dummy Entra secret",
      method: "passkey on the core OAuth authorize page, then the OAuth JWT as a bearer on the instance origin",
      passkey_setup_link: `${passkeys.link.origin}${passkeys.link.pathname}?token=<redacted>`,
      passkey_registration: { "127.0.0.1": passkeys.onAddress, localhost: passkeys.onLocalhost },
      oauth_client_registration: { status: registered.status, body: describeBody(client) },
      authorize_callback_query: [...hit.url.searchParams.keys()],
      state_returned: hit.url.searchParams.get("state") === state,
      cookies_after_sign_in: cookies,
      token: { status: token.status, body: describeBody(issued) },
      jwt_claims: isRecord(claims) ? { names: Object.keys(claims).sort(), aud: claims.aud } : null,
    },
  }
}

async function roundTrip(run: Run) {
  run.section = "round-trip"
  await run.page.goto(`${run.web}${devicePath}?redirect=${encodeURIComponent(callbackUrl(run))}`)
  const consent = await readDevicePage(run)
  await run.page.locator('form[action$="/approve"] button').click()
  const hit = await takeHit(run.hits, "/cb")
  const code = keepSecret(run, hit.url.searchParams.get("code") ?? "")
  const traded = await postJson(`${run.api}/v1/auth/bridge/session-pat`, { code, device_name: captureLabel })
  const pat = keepSecret(run, stringField(traded.body, "pat"))
  const minted = await patToJwt(run, pat)
  const again = await postJson(`${run.api}/v1/auth/bridge/session-pat`, { code, device_name: captureLabel })
  console.log(`  consent: "${consent.title}", forms ${consent.forms.map((form) => `${form.action} [${form.fields.join(",")}]`).join(", ")}`)
  console.log(`  callback ${hit.method} ${hit.url.pathname} ?${[...hit.url.searchParams.keys()].join("&")} (code ${code.length} chars)`)
  console.log(`  session-pat ${traded.status}: PAT ${truncate(pat)}; /pat ${minted.status}: JWT ${truncate(minted.token)} ttl ${minted.ttl}s`)
  if (traded.status !== 200 || minted.status !== 200 || minted.token === "") throw new Error("the device-link code did not become a PAT and a JWT")
  console.log("  PAT minted a JWT")
  console.log(`  second use of the code: ${again.status} ${stringField(again.body, "message")}`)
  return {
    pat,
    record: {
      consent,
      approve: run.steps.filter((step) => step.section === "round-trip" && step.method === "POST"),
      callback: {
        method: hit.method,
        path: hit.url.pathname,
        query: [...hit.url.searchParams.keys()],
        code_format: /^[0-9a-f]{64}$/.test(code) ? "64 lowercase hex characters" : `unexpected (${code.length} characters)`,
        request_headers: hit.headers,
        referer: hit.referer === null ? null : redactUrl(hit.referer, run.scope),
        carries_bearer: hit.headers.includes("authorization"),
      },
      session_pat: { request: ["code", "device_name"], status: traded.status, body: describeBody(traded.body) },
      pat_to_jwt: { status: minted.status, body: minted.body },
      second_use: { status: again.status, body: describeBody(again.body) },
    },
  }
}

