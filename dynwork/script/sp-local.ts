#!/usr/bin/env bun
// Two disposable systemprompt 0.76 instances (alpha and beta) on this Mac, for every DynWork phase that talks to a real
// server. Nothing here reaches a Dynapps environment: the image, a PostgreSQL 18 and loopback ports.
//
//   bun dynwork/script/sp-local.ts up        start PostgreSQL and both instances, wait until they answer
//   bun dynwork/script/sp-local.ts seed      user, PAT, exchange code and content on each instance
//   bun dynwork/script/sp-local.ts check     health, PAT to JWT, signed manifest, ETag and 304, content counts
//   bun dynwork/script/sp-local.ts status    containers and whether each instance answers
//   bun dynwork/script/sp-local.ts code [alpha|beta]   a fresh exchange code (10 minutes, single use)
//   bun dynwork/script/sp-local.ts down      remove containers, volumes and the generated env file
//
// Secrets and ports are generated by `up` into dynwork/test/sp-local/.env.local (gitignored); `seed` adds the URLs, the
// user and the PAT. See dynwork/test/sp-local/README.md for what the image needs to run.
import { $ } from "bun"
import { createPublicKey, randomBytes, verify } from "node:crypto"
import { rm } from "node:fs/promises"
import path from "node:path"

const dir = path.resolve(import.meta.dir, "../test/sp-local")

const envFile = path.join(dir, ".env.local")

const composeFile = path.join(dir, "compose.yml")

const project = "dynwork-sp-local"

export const instances = ["alpha", "beta"] as const

export type Instance = (typeof instances)[number]

export const userEmail = "dev@dynapps.test"

// What each instance's authoring tree under content/<instance> must deliver to userEmail. The ids come from those trees.
export const expected = {
  alpha: {
    skills: ["alpha_notes", "alpha_review"],
    agents: ["alpha_helper"],
    mcp: ["alpha-docs"],
    rules: ["alpha_conventions"],
  },
  beta: {
    skills: ["beta_review", "beta_triage"],
    agents: ["beta_helper"],
    mcp: ["beta-docs"],
    rules: ["beta_conventions"],
  },
} as const satisfies Record<Instance, Record<"skills" | "agents" | "mcp" | "rules", readonly string[]>>

// Ports other things on this Mac already own: DynWork's service, and the smoke073 containers.
const reservedPorts = [17495, 18080, 15000]

if (import.meta.main) await main(process.argv.slice(2))

async function main(args: string[]) {
  const command = args[0]
  if (command === "up") return up()
  if (command === "seed") return seed()
  if (command === "check") return check()
  if (command === "status") return status()
  if (command === "code") return code(args[1] === undefined ? instances : [requireInstance(args[1])])
  if (command === "down") return down()
  console.error("usage: sp-local.ts up|seed|check|status|code [alpha|beta]|down")
  process.exit(2)
}

// ---------------------------------------------------------------------------------------------------------------------
// Pure helpers, exported for the tests

export function parseEnv(text: string) {
  return Object.fromEntries(
    text
      .split("\n")
      .filter((line) => line.trim() !== "" && !line.startsWith("#"))
      .map((line) => [line.slice(0, line.indexOf("=")), line.slice(line.indexOf("=") + 1)]),
  )
}

export function formatEnv(values: Record<string, string>) {
  return Object.entries(values)
    .map((entry) => `${entry[0]}=${entry[1]}`)
    .join("\n")
    .concat("\n")
}

// The CLI's --json output is a presentation card: one `heading` and `content` per field.
export function cardField(output: string, heading: string) {
  const card: { sections: { heading: string; content: unknown }[] } = JSON.parse(output)
  const section = card.sections.find((item) => item.heading === heading)
  if (section === undefined || typeof section.content !== "string") throw new Error(`the CLI output has no "${heading}"`)
  return section.content
}

export function jwtExpiry(token: string) {
  const claims: { exp: number } = JSON.parse(Buffer.from(token.split(".")[1] ?? "", "base64url").toString())
  return new Date(claims.exp * 1000)
}

export function truncate(secret: string) {
  return `${secret.slice(0, 12)}…`
}

type Entry = { id?: string; name?: string }

export type Manifest = {
  skills: Entry[]
  agents: Entry[]
  managed_mcp_servers: Entry[]
  rules?: Entry[]
}

export function manifestIds(manifest: Manifest) {
  const ids = (entries: Entry[] | undefined) => (entries ?? []).map((entry) => entry.id ?? entry.name ?? "")
  return {
    skills: ids(manifest.skills),
    agents: ids(manifest.agents),
    mcp: ids(manifest.managed_mcp_servers),
    rules: ids(manifest.rules),
  }
}

// Ids the instance should deliver but does not.
export function missing(instance: Instance, manifest: Manifest) {
  const have = manifestIds(manifest)
  return (["skills", "agents", "mcp", "rules"] as const).flatMap((group) => {
    const wanted: readonly string[] = expected[instance][group]
    return wanted.filter((id) => !have[group].includes(id)).map((id) => `${group}/${id}`)
  })
}

// The envelope carries a JCS string and an ed25519 signature over its exact bytes; the key is the raw 32 bytes in base64.
export function signatureValid(envelope: { payload: string; signature: string }, pubkey: string) {
  const spkiPrefix = Buffer.from("302a300506032b6570032100", "hex")
  const key = createPublicKey({
    key: Buffer.concat([spkiPrefix, Buffer.from(pubkey, "base64")]),
    format: "der",
    type: "spki",
  })
  return verify(null, Buffer.from(envelope.payload), key, Buffer.from(envelope.signature, "base64"))
}

export async function freePort(taken: number[], from: number) {
  const candidates = Array.from({ length: 100 }, (_, index) => from + index).filter(
    (port) => !taken.includes(port) && !reservedPorts.includes(port),
  )
  for (const port of candidates) {
    if (await canListen(port)) return port
  }
  throw new Error(`no free port from ${from}`)
}

async function canListen(port: number) {
  const server = await Promise.resolve()
    .then(() => Bun.listen({ hostname: "127.0.0.1", port, socket: { data() {} } }))
    .catch(() => undefined)
  server?.stop(true)
  return server !== undefined
}

// ---------------------------------------------------------------------------------------------------------------------
// Commands

async function up() {
  const env = await loadEnv()
  const alpha = env.SP_ALPHA_PORT ? Number(env.SP_ALPHA_PORT) : await freePort([], 18101)
  const beta = env.SP_BETA_PORT ? Number(env.SP_BETA_PORT) : await freePort([alpha], 18101)
  await saveEnv({
    ...env,
    SP_DB_PASSWORD: env.SP_DB_PASSWORD ?? randomBytes(16).toString("hex"),
    SP_PROVIDER_KEY: env.SP_PROVIDER_KEY ?? `sk-ant-local-${randomBytes(12).toString("hex")}`,
    SP_ENTRA_SECRET: env.SP_ENTRA_SECRET ?? `local-${randomBytes(12).toString("hex")}`,
    SP_ALPHA_PORT: String(alpha),
    SP_BETA_PORT: String(beta),
  })
  await compose("up", "-d")
  await Promise.all(instances.map((instance) => waitReady(instance)))
  console.log(`up: alpha ${url(await loadEnv(), "alpha")}, beta ${url(await loadEnv(), "beta")}`)
}

async function seed() {
  for (const instance of instances) {
    await seedInstance(instance)
  }
}

async function seedInstance(instance: Instance) {
  const label = instance.toUpperCase()
  await waitReady(instance)
  await cli(instance, "admin", "users", "create", "--name", "dev", "--email", userEmail, "--full-name", "Dev User", "--if-not-exists")
  const users: { items: { id: string; email: string }[] } = JSON.parse(await cli(instance, "admin", "users", "list", "--json"))
  const user = users.items.find((item) => item.email === userEmail)
  if (user === undefined) throw new Error(`${instance}: ${userEmail} was not created`)

  const env = await loadEnv()
  const kept = env[`SP_${label}_PAT`]
  const pat =
    kept !== undefined && (await exchangePat(url(env, instance), kept)) !== undefined
      ? kept
      : cardField(
          await cli(instance, "admin", "users", "api-key", "issue", "--user", user.id, "--name", `dynwork-local-${Date.now()}`, "--json"),
          "secret",
        )

  const issued = await cli(instance, "admin", "bridge", "issue-code", "--user-id", userEmail, "--json")
  await saveEnv({
    ...env,
    [`SP_${label}_URL`]: url(env, instance),
    [`SP_${label}_USER_EMAIL`]: userEmail,
    [`SP_${label}_USER_ID`]: user.id,
    [`SP_${label}_PAT`]: pat,
    [`SP_${label}_EXCHANGE_CODE`]: cardField(issued, "code"),
    [`SP_${label}_EXCHANGE_CODE_EXPIRES`]: cardField(issued, "expires_at"),
  })

  const pending = await missingContent(instance, url(env, instance), pat)
  if (pending.length > 0) await loadContent(instance, url(env, instance), pat)
  console.log(`seed ${instance}: ${userEmail}, PAT ${truncate(pat)}, content ${pending.length > 0 ? "loaded" : "already there"}`)
}

// The authoring tree under content/<instance> goes through the image's own `core marketplace import`; the agent through
// `admin agents create`. The server reads its services tree at boot, so it restarts once the declarations are applied.
async function loadContent(instance: Instance, base: string, pat: string) {
  const agent = expected[instance].agents[0]
  await sh(instance, "rm -rf /tmp/content /tmp/out && mkdir -p /tmp/content")
  await compose("cp", `${path.join(dir, "content", instance)}/.`, `${instance}:/tmp/content`)
  await cli(instance, "core", "marketplace", "import", "--from", "/tmp/content", "--into", "/tmp/out", "--strict")
  if ((await shExit(instance, `test -f /app/services/agents/${agent}.yaml`)) !== 0) {
    await cli(
      instance,
      "admin",
      "agents",
      "create",
      "--name",
      agent,
      "--display-name",
      `${instance} helper`,
      "--description",
      `Local test agent of the ${instance} instance`,
      "--port",
      "9101",
      "--enabled",
      "--system-prompt",
      `You are the ${instance} helper of the local DynWork harness.`,
      "--mcp-server",
      expected[instance].mcp[0],
      "--skill",
      expected[instance].skills[0],
      "--non-interactive",
    )
  }
  // The importer writes its own aggregator; the instance's config.yaml keeps the shipped one and gains two includes.
  await sh(
    instance,
    [
      "set -e",
      "cd /tmp/out",
      "for d in marketplaces plugins skills rules mcp; do mkdir -p /app/services/$d; cp -r $d/. /app/services/$d/; done",
      ...[`../mcp/${expected[instance].mcp[0]}.yaml`, `../agents/${agent}.yaml`].map(
        (include) =>
          `grep -q -F -e '- ${include}' /app/services/config/config.yaml || sed -i 's|^includes:|includes:\\n  - ${include}|' /app/services/config/config.yaml`,
      ),
    ].join("\n"),
  )
  await cli(instance, "admin", "config", "apply", "--reason", "sp-local seed")
  await compose("restart", instance)
  await waitReady(instance)
  const stillMissing = await missingContent(instance, base, pat)
  if (stillMissing.length > 0) throw new Error(`${instance}: the manifest still lacks ${stillMissing.join(", ")}`)
}

async function check() {
  const env = await loadEnv()
  const failures: string[] = []
  for (const instance of instances) {
    failures.push(...(await checkInstance(instance, env)))
  }
  if (failures.length > 0) {
    console.error(`check failed:\n${failures.map((failure) => `  - ${failure}`).join("\n")}`)
    process.exit(1)
  }
  console.log("check ok")
}

async function checkInstance(instance: Instance, env: Record<string, string>) {
  const base = url(env, instance)
  const pat = env[`SP_${instance.toUpperCase()}_PAT`]
  const lines = [`${instance} ${base}`]
  const failures: string[] = []
  const fail = (message: string) => failures.push(`${instance}: ${message}`)
  const report = () => console.log(lines.join("\n"))

  if (pat === undefined) {
    fail("no PAT in .env.local, run seed")
    return failures
  }

  const health = await fetch(`${base}/api/v1/health`).catch(() => undefined)
  lines.push(`  health ${health?.status}`)
  if (health?.status !== 200) fail(`health answered ${health?.status}`)

  const session = await exchangePat(base, pat)
  if (session === undefined) {
    fail("the PAT was not exchanged for a JWT")
    report()
    return failures
  }
  lines.push(`  PAT ${truncate(pat)} -> JWT ${truncate(session.token)} ttl ${session.ttl}s, expires ${jwtExpiry(session.token).toISOString()}`)

  const headers = { authorization: `Bearer ${session.token}` }
  const manifest = await fetch(`${base}/v1/bridge/manifest`, { headers: { ...headers, "cache-control": "no-cache" } })
  const etag = manifest.headers.get("etag")
  lines.push(`  manifest ${manifest.status} etag ${etag}`)
  if (manifest.status !== 200 || etag === null) {
    fail(`manifest answered ${manifest.status} with etag ${etag}`)
    report()
    return failures
  }
  const envelope: { payload: string; signature: string } = JSON.parse(await manifest.text())
  const pubkey: { pubkey: string } = JSON.parse(await (await fetch(`${base}/v1/bridge/pubkey`)).text())
  const signed = signatureValid(envelope, pubkey.pubkey)
  lines.push(`  manifest signature ${signed ? "valid" : "INVALID"}`)
  if (!signed) fail("the manifest signature does not verify against /v1/bridge/pubkey")

  const again = await fetch(`${base}/v1/bridge/manifest`, { headers: { ...headers, "if-none-match": etag } })
  lines.push(`  manifest with If-None-Match ${again.status}`)
  if (again.status !== 304) fail(`If-None-Match answered ${again.status}, expected 304`)

  const content: Manifest = JSON.parse(envelope.payload)
  const have = manifestIds(content)
  lines.push(`  skills ${have.skills.length}, agents ${have.agents.length}, mcp ${have.mcp.length}, rules ${have.rules.length}`)
  if (have.skills.length < 2 || have.agents.length < 1 || have.mcp.length < 1) fail("fewer skills, agents or mcp than seeded")
  missing(instance, content).forEach((id) => fail(`the manifest lacks ${id}`))
  report()
  return failures
}

async function status() {
  const env = await loadEnv()
  console.log((await compose("ps", "-a").nothrow().text()).trim())
  for (const instance of instances) {
    if (env[`SP_${instance.toUpperCase()}_PORT`] === undefined) continue
    const health = await fetch(`${url(env, instance)}/api/v1/health`).catch(() => undefined)
    console.log(`${instance} ${url(env, instance)} health ${health?.status ?? "unreachable"}`)
  }
}

async function code(selected: readonly Instance[]) {
  const env = await loadEnv()
  const next = { ...env }
  for (const instance of selected) {
    const issued = await cli(instance, "admin", "bridge", "issue-code", "--user-id", userEmail, "--json")
    next[`SP_${instance.toUpperCase()}_EXCHANGE_CODE`] = cardField(issued, "code")
    next[`SP_${instance.toUpperCase()}_EXCHANGE_CODE_EXPIRES`] = cardField(issued, "expires_at")
    console.log(`${instance}: exchange code ${truncate(cardField(issued, "code"))} valid until ${cardField(issued, "expires_at")}`)
  }
  await saveEnv(next)
}

async function down() {
  const env = await loadEnv()
  // compose still wants the variables it interpolates when the env file is already gone
  await $`docker compose -p ${project} -f ${composeFile} down -v --remove-orphans`.env({
    ...process.env,
    SP_DB_PASSWORD: env.SP_DB_PASSWORD ?? "unused",
    SP_PROVIDER_KEY: "unused",
    SP_ENTRA_SECRET: "unused",
    SP_ALPHA_PORT: env.SP_ALPHA_PORT ?? "0",
    SP_BETA_PORT: env.SP_BETA_PORT ?? "0",
  })
  // the PAT and the secrets belong to the databases that were just dropped
  await rm(envFile, { force: true })
  console.log("down: containers, volumes and .env.local removed")
}

// ---------------------------------------------------------------------------------------------------------------------
// Docker and HTTP plumbing

function compose(...args: string[]) {
  return $`docker compose -p ${project} -f ${composeFile} --env-file ${envFile} ${args}`.quiet()
}

// Runs the instance's own CLI in its container; stdout is the command's result, its logs go to stderr.
async function cli(instance: Instance, ...args: string[]) {
  const result = await compose("exec", "-T", instance, "/app/bin/systemprompt", ...args).nothrow()
  if (result.exitCode !== 0) throw new Error(`${instance}: systemprompt ${args.slice(0, 3).join(" ")} failed\n${result.stderr.toString().slice(-600)}`)
  return result.stdout.toString()
}

async function sh(instance: Instance, script: string) {
  const result = await compose("exec", "-T", instance, "sh", "-c", script).nothrow()
  if (result.exitCode !== 0) throw new Error(`${instance}: ${script.split("\n")[0]} failed\n${result.stderr.toString().slice(-600)}`)
}

async function shExit(instance: Instance, script: string) {
  return (await compose("exec", "-T", instance, "sh", "-c", script).nothrow()).exitCode
}

async function waitReady(instance: Instance) {
  const base = url(await loadEnv(), instance)
  const deadline = Date.now() + 240_000
  while (Date.now() < deadline) {
    // the bridge routes mount last, so they answer only once the instance is really up
    const response = await fetch(`${base}/v1/auth/bridge/capabilities`).catch(() => undefined)
    if (response?.status === 200) return
    await Bun.sleep(1000)
  }
  throw new Error(`${instance} did not answer at ${base} within 240 s`)
}

export async function exchangePat(base: string, pat: string) {
  const response = await fetch(`${base}/v1/auth/bridge/pat`, { method: "POST", headers: { authorization: `Bearer ${pat}` } }).catch(
    () => undefined,
  )
  if (response?.status !== 200) return undefined
  const body: { token: string; ttl: number } = JSON.parse(await response.text())
  return body
}

async function missingContent(instance: Instance, base: string, pat: string) {
  const session = await exchangePat(base, pat)
  if (session === undefined) return ["a JWT"]
  const response = await fetch(`${base}/v1/bridge/manifest`, {
    headers: { authorization: `Bearer ${session.token}`, "cache-control": "no-cache" },
  })
  const envelope: { payload: string } = JSON.parse(await response.text())
  return missing(instance, JSON.parse(envelope.payload))
}

async function loadEnv(): Promise<Record<string, string>> {
  const file = Bun.file(envFile)
  return (await file.exists()) ? parseEnv(await file.text()) : {}
}

async function saveEnv(values: Record<string, string>) {
  await Bun.write(envFile, formatEnv(values))
  await $`chmod 600 ${envFile}`
}

function url(env: Record<string, string>, instance: Instance) {
  return `http://127.0.0.1:${env[`SP_${instance.toUpperCase()}_PORT`]}`
}

function requireInstance(name: string) {
  const found = instances.find((instance) => instance === name)
  if (found === undefined) throw new Error(`unknown instance "${name}", expected alpha or beta`)
  return found
}
