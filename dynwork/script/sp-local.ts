export function parseEnv(text: string) {
  return Object.fromEntries(
    text
      .split("\n")
      .filter((line) => line.trim() !== "" && !line.startsWith("#"))
      .map((line) => [line.slice(0, line.indexOf("=")), line.slice(line.indexOf("=") + 1)]),
  )
}

export function formatEnv(values: Record<string, string>) {
  return Object.entries(values)
    .map((entry) => `${entry[0]}=${entry[1]}`)
    .join("\n")
    .concat("\n")
}

// The CLI's --json output is a presentation card: one `heading` and `content` per field.
export function cardField(output: string, heading: string) {
  const card: { sections: { heading: string; content: unknown }[] } = JSON.parse(output)
  const section = card.sections.find((item) => item.heading === heading)
  if (section === undefined || typeof section.content !== "string") throw new Error(`the CLI output has no "${heading}"`)
  return section.content
}

export function jwtExpiry(token: string) {
  const claims: { exp: number } = JSON.parse(Buffer.from(token.split(".")[1] ?? "", "base64url").toString())
  return new Date(claims.exp * 1000)
}

export function truncate(secret: string) {
  return `${secret.slice(0, 12)}…`
}

type Entry = { id?: string; name?: string }

export type Manifest = {
  skills: Entry[]
  agents: Entry[]
  managed_mcp_servers: Entry[]
  rules?: Entry[]
}

export function manifestIds(manifest: Manifest) {
  const ids = (entries: Entry[] | undefined) => (entries ?? []).map((entry) => entry.id ?? entry.name ?? "")
  return {
    skills: ids(manifest.skills),
    agents: ids(manifest.agents),
    mcp: ids(manifest.managed_mcp_servers),
    rules: ids(manifest.rules),
  }
}

// Ids the instance should deliver but does not.
export function missing(instance: Instance, manifest: Manifest) {
  const have = manifestIds(manifest)
  return (["skills", "agents", "mcp", "rules"] as const).flatMap((group) => {
    const wanted: readonly string[] = expected[instance][group]
    return wanted.filter((id) => !have[group].includes(id)).map((id) => `${group}/${id}`)
  })
}

// The envelope carries a JCS string and an ed25519 signature over its exact bytes; the key is the raw 32 bytes in base64.
export function signatureValid(envelope: { payload: string; signature: string }, pubkey: string) {
  const spkiPrefix = Buffer.from("302a300506032b6570032100", "hex")
  const key = createPublicKey({
    key: Buffer.concat([spkiPrefix, Buffer.from(pubkey, "base64")]),
    format: "der",
    type: "spki",
  })
  return verify(null, Buffer.from(envelope.payload), key, Buffer.from(envelope.signature, "base64"))
}

export async function freePort(taken: number[], from: number) {
  const candidates = Array.from({ length: 100 }, (_, index) => from + index).filter(
    (port) => !taken.includes(port) && !reservedPorts.includes(port),
  )
  for (const port of candidates) {
    if (await canListen(port)) return port
  }
  throw new Error(`no free port from ${from}`)
}

async function canListen(port: number) {
  const server = await Promise.resolve()
    .then(() => Bun.listen({ hostname: "127.0.0.1", port, socket: { data() {} } }))
    .catch(() => undefined)
  server?.stop(true)
  return server !== undefined
}

// What the capture may keep from a URL: the instance origin as <instance>, the loopback listener's port as <port>, query
// names, and only the values that are protocol vocabulary. A `redirect` value is itself a URL and is redacted the same way.
export type Scope = { origins: string[]; port: number }

export function redactUrl(raw: string, scope: Scope): string {
  const parsed = URL.parse(raw, relativeBase)
  if (parsed === null) return "<unparsable url>"
  const origin =
    parsed.origin === relativeBase
      ? ""
      : scope.origins.includes(parsed.origin)
        ? "<instance>"
        : `${parsed.protocol}//${parsed.host.replace(`:${scope.port}`, ":<port>")}`
  const query = [...parsed.searchParams].map((pair) => {
    if (pair[0] === "redirect") return `redirect=${redactUrl(pair[1], scope)}`
    return `${pair[0]}=${keptQuery.includes(pair[0]) ? pair[1] : "<redacted>"}`
  })
  return `${origin}${parsed.pathname}${query.length > 0 ? `?${query.join("&")}` : ""}`
}

// A JSON body as the fixture records it: same keys (sorted, the server's map order varies) and numbers, secrets and
// per-run values replaced by what they are.
export function describeBody(value: unknown, key = ""): unknown {
  if (Array.isArray(value)) return value.map((item) => describeBody(item))
  if (typeof value === "object" && value !== null)
    return Object.fromEntries(
      Object.entries(value)
        .sort((left, right) => left[0].localeCompare(right[0]))
        .map((entry) => [entry[0], describeBody(entry[1], entry[0])]),
    )
  if (typeof value === "number" && /(_at|^iat|^exp|^nbf)$/.test(key)) return "<timestamp>"
  if (typeof value !== "string") return value
  if (value.startsWith("sp-live-")) return "<pat>"
  if (/^eyJ[\w-]*\.[\w-]*\.[\w-]*$/.test(value)) return "<jwt>"
  if (/^[0-9a-f]{64}$/.test(value)) return "<code>"
  if (/^\d{4}-\d{2}-\d{2}T/.test(value)) return "<timestamp>"
  return keptFields.includes(key) ? value : "<string>"
}

// Rendered page text as the fixture records it: whitespace collapsed, the listener port and codes redacted, and the
// seconds a code has left rounded to 10 (the paste page renders a second after the code is minted).
export function scrubText(text: string, scope: Scope) {
  return text
    .replaceAll(`:${scope.port}`, ":<port>")
    .replace(/[0-9a-f]{64}/g, "<code>")
    .replace(/(\d+)\s+seconds/g, (_, seconds: string) => `${Math.round(Number(seconds) / 10) * 10} seconds`)
    .replace(/\s+/g, " ")
    .trim()
}

// Leaf paths that differ between two fixtures, ignoring when each was captured.
export function fixtureChanges(before: unknown, after: unknown, at = ""): string[] {
  if (JSON.stringify(before) === JSON.stringify(after)) return []
  if (!isRecord(before) || !isRecord(after)) return [at === "" ? "(root)" : at]
  return [...new Set([...Object.keys(before), ...Object.keys(after)])]
    .filter((key) => key !== "captured_at")
    .flatMap((key) => fixtureChanges(before[key], after[key], at === "" ? key : `${at}.${key}`))
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value)
}

// The secrets of a run that appear in a text meant to be committed.
export function leaks(text: string, secrets: string[]) {
  return secrets.filter((secret) => secret.length >= 8 && text.includes(secret))
}

