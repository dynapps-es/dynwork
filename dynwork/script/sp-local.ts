// The compose project, the first port to try and the env file of one stack. The default stack keeps the names it always
// had, so a run without the variables is unchanged.
export function stackSettings(env: Record<string, string | undefined>) {
  const project = env.SP_LOCAL_PROJECT ?? defaultProject
  if (!/^[a-z0-9][a-z0-9_-]*$/.test(project))
    throw new Error(`SP_LOCAL_PROJECT "${project}" is not a valid compose project name`)
  const base = env.SP_LOCAL_PORT_BASE ?? String(defaultPortBase)
  const portBase = Number(base)
  if (!/^\d+$/.test(base) || portBase < 1024 || portBase > 65400)
    throw new Error(`SP_LOCAL_PORT_BASE "${base}" is not a port from 1024 to 65400`)
  return { project, portBase, envName: project === defaultProject ? ".env.local" : `.env.${project}.local` }
}

