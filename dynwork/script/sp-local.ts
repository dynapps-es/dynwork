async function up() {
  const env = await loadEnv()
  const alpha = env.SP_ALPHA_PORT ? Number(env.SP_ALPHA_PORT) : await freePort([], stack.portBase)
  const beta = env.SP_BETA_PORT ? Number(env.SP_BETA_PORT) : await freePort([alpha], stack.portBase)
  await saveEnv({
    ...env,
    SP_DB_PASSWORD: env.SP_DB_PASSWORD ?? randomBytes(16).toString("hex"),
    SP_PROVIDER_KEY: env.SP_PROVIDER_KEY ?? `sk-ant-local-${randomBytes(12).toString("hex")}`,
    SP_ENTRA_SECRET: env.SP_ENTRA_SECRET ?? `local-${randomBytes(12).toString("hex")}`,
    SP_ALPHA_PORT: String(alpha),
    SP_BETA_PORT: String(beta),
  })
  await compose("up", "-d")
  await Promise.all(instances.map((instance) => waitReady(instance)))
  console.log(`up: alpha ${url(await loadEnv(), "alpha")}, beta ${url(await loadEnv(), "beta")}`)
}

