// A request to the instance as the signed-in user, without following redirects.
async function asUser(run: Run, jwt: string, target: string, form?: URLSearchParams) {
  const response = await fetch(`${run.api}${target}`, {
    method: form === undefined ? "GET" : "POST",
    body: form,
    headers: { authorization: `Bearer ${jwt}` },
    redirect: "manual",
  })
  const rawLocation = response.headers.get("location") ?? undefined
  keepSecret(run, URL.parse(rawLocation ?? "")?.searchParams.get("code") ?? "")
  const html = await response.text()
  return {
    status: response.status,
    rawLocation,
    location: rawLocation === undefined ? undefined : redactUrl(rawLocation, run.scope),
    title: html.match(/<h1[^>]*>([^<]*)</)?.[1]?.trim(),
    html,
  }
}

async function postJson(target: string, body: unknown) {
  const response = await fetch(target, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(body) })
  const parsed: unknown = await response.json().catch(() => null)
  return { status: response.status, body: parsed }
}

async function patToJwt(run: Run, pat: string) {
  const response = await fetch(`${run.api}/v1/auth/bridge/pat`, { method: "POST", headers: { authorization: `Bearer ${pat}` } })
  const body: unknown = await response.json().catch(() => null)
  const token = keepSecret(run, stringField(body, "token"))
  keepSecret(run, stringField(body, "device_token"))
  return { status: response.status, body: describeBody(body), token, ttl: isRecord(body) ? body.ttl : undefined }
}

async function takeHit(hits: Hit[], pathname: string) {
  const deadline = Date.now() + 15_000
  while (Date.now() < deadline) {
    const index = hits.findIndex((hit) => hit.url.pathname === pathname)
    const hit = hits[index]
    if (hit !== undefined) {
      hits.splice(index, 1)
      return hit
    }
    await Bun.sleep(100)
  }
  throw new Error(`the loopback listener got no request on ${pathname} within 15 s`)
}

