async function seedInstance(instance: Instance) {
  const label = instance.toUpperCase()
  await waitReady(instance)
  await cli(instance, "admin", "users", "create", "--name", "dev", "--email", userEmail, "--full-name", "Dev User", "--if-not-exists")
  const users: { items: { id: string; email: string }[] } = JSON.parse(await cli(instance, "admin", "users", "list", "--json"))
  const user = users.items.find((item) => item.email === userEmail)
  if (user === undefined) throw new Error(`${instance}: ${userEmail} was not created`)

  const env = await loadEnv()
  const kept = env[`SP_${label}_PAT`]
  const pat =
    kept !== undefined && (await exchangePat(url(env, instance), kept)) !== undefined
      ? kept
      : cardField(
          await cli(instance, "admin", "users", "api-key", "issue", "--user", user.id, "--name", `dynwork-local-${Date.now()}`, "--json"),
          "secret",
        )

  const issued = await cli(instance, "admin", "bridge", "issue-code", "--user-id", userEmail, "--json")
  await saveEnv({
    ...env,
    [`SP_${label}_URL`]: url(env, instance),
    [`SP_${label}_USER_EMAIL`]: userEmail,
    [`SP_${label}_USER_ID`]: user.id,
    [`SP_${label}_PAT`]: pat,
    [`SP_${label}_EXCHANGE_CODE`]: cardField(issued, "code"),
    [`SP_${label}_EXCHANGE_CODE_EXPIRES`]: cardField(issued, "expires_at"),
  })

  const pending = await missingContent(instance, url(env, instance), pat)
  if (pending.length > 0) await loadContent(instance, url(env, instance), pat)
  console.log(`seed ${instance}: ${userEmail}, PAT ${truncate(pat)}, content ${pending.length > 0 ? "loaded" : "already there"}`)
}

// The authoring tree under content/<instance> goes through the image's own `core marketplace import`; the agent through
// `admin agents create`. The server reads its services tree at boot, so it restarts once the declarations are applied.
async function loadContent(instance: Instance, base: string, pat: string) {
  const agent = expected[instance].agents[0]
  await sh(instance, "rm -rf /tmp/content /tmp/out && mkdir -p /tmp/content")
  await compose("cp", `${path.join(dir, "content", instance)}/.`, `${instance}:/tmp/content`)
  await cli(instance, "core", "marketplace", "import", "--from", "/tmp/content", "--into", "/tmp/out", "--strict")
  if ((await shExit(instance, `test -f /app/services/agents/${agent}.yaml`)) !== 0) {
    await cli(
      instance,
      "admin",
      "agents",
      "create",
      "--name",
      agent,
      "--display-name",
      `${instance} helper`,
      "--description",
      `Local test agent of the ${instance} instance`,
      "--port",
      "9101",
      "--enabled",
      "--system-prompt",
      `You are the ${instance} helper of the local DynWork harness.`,
      "--mcp-server",
      expected[instance].mcp[0],
      "--skill",
      expected[instance].skills[0],
      "--non-interactive",
    )
  }
  // The importer writes its own aggregator; the instance's config.yaml keeps the shipped one and gains two includes.
  await sh(
    instance,
    [
      "set -e",
      "cd /tmp/out",
      "for d in marketplaces plugins skills rules mcp; do mkdir -p /app/services/$d; cp -r $d/. /app/services/$d/; done",
      ...[`../mcp/${expected[instance].mcp[0]}.yaml`, `../agents/${agent}.yaml`].map(
        (include) =>
          `grep -q -F -e '- ${include}' /app/services/config/config.yaml || sed -i 's|^includes:|includes:\\n  - ${include}|' /app/services/config/config.yaml`,
      ),
    ].join("\n"),
  )
  await cli(instance, "admin", "config", "apply", "--reason", "sp-local seed")
  await compose("restart", instance)
  await waitReady(instance)
  const stillMissing = await missingContent(instance, base, pat)
  if (stillMissing.length > 0) throw new Error(`${instance}: the manifest still lacks ${stillMissing.join(", ")}`)
}

async function check() {
  const env = await loadEnv()
  const failures: string[] = []
  for (const instance of instances) {
    failures.push(...(await checkInstance(instance, env)))
  }
  if (failures.length > 0) {
    console.error(`check failed:\n${failures.map((failure) => `  - ${failure}`).join("\n")}`)
    process.exit(1)
  }
  console.log("check ok")
}

async function checkInstance(instance: Instance, env: Record<string, string>) {
  const base = url(env, instance)
  const pat = env[`SP_${instance.toUpperCase()}_PAT`]
  const lines = [`${instance} ${base}`]
  const failures: string[] = []
  const fail = (message: string) => failures.push(`${instance}: ${message}`)
  const report = () => console.log(lines.join("\n"))

  if (pat === undefined) {
    fail(`no PAT in ${stack.envName}, run seed`)
    return failures
  }

  const health = await fetch(`${base}/api/v1/health`).catch(() => undefined)
  lines.push(`  health ${health?.status}`)
  if (health?.status !== 200) fail(`health answered ${health?.status}`)

  const session = await exchangePat(base, pat)
  if (session === undefined) {
    fail("the PAT was not exchanged for a JWT")
    report()
    return failures
  }
  lines.push(`  PAT ${truncate(pat)} -> JWT ${truncate(session.token)} ttl ${session.ttl}s, expires ${jwtExpiry(session.token).toISOString()}`)

  const headers = { authorization: `Bearer ${session.token}` }
  const manifest = await fetch(`${base}/v1/bridge/manifest`, { headers: { ...headers, "cache-control": "no-cache" } })
  const etag = manifest.headers.get("etag")
  lines.push(`  manifest ${manifest.status} etag ${etag}`)
  if (manifest.status !== 200 || etag === null) {
    fail(`manifest answered ${manifest.status} with etag ${etag}`)
    report()
    return failures
  }
  const envelope: { payload: string; signature: string } = JSON.parse(await manifest.text())
  const pubkey: { pubkey: string } = JSON.parse(await (await fetch(`${base}/v1/bridge/pubkey`)).text())
  const signed = signatureValid(envelope, pubkey.pubkey)
  lines.push(`  manifest signature ${signed ? "valid" : "INVALID"}`)
  if (!signed) fail("the manifest signature does not verify against /v1/bridge/pubkey")

  const again = await fetch(`${base}/v1/bridge/manifest`, { headers: { ...headers, "if-none-match": etag } })
  lines.push(`  manifest with If-None-Match ${again.status}`)
  if (again.status !== 304) fail(`If-None-Match answered ${again.status}, expected 304`)

  const content: Manifest = JSON.parse(envelope.payload)
  const have = manifestIds(content)
  lines.push(`  skills ${have.skills.length}, agents ${have.agents.length}, mcp ${have.mcp.length}, rules ${have.rules.length}`)
  if (have.skills.length < 2 || have.agents.length < 1 || have.mcp.length < 1) fail("fewer skills, agents or mcp than seeded")
  missing(instance, content).forEach((id) => fail(`the manifest lacks ${id}`))
  report()
  return failures
}

async function status() {
  const env = await loadEnv()
  console.log((await compose("ps", "-a").nothrow().text()).trim())
  for (const instance of instances) {
    if (env[`SP_${instance.toUpperCase()}_PORT`] === undefined) continue
    const health = await fetch(`${url(env, instance)}/api/v1/health`).catch(() => undefined)
    console.log(`${instance} ${url(env, instance)} health ${health?.status ?? "unreachable"}`)
  }
}

async function code(selected: readonly Instance[]) {
  const env = await loadEnv()
  const next = { ...env }
  for (const instance of selected) {
    const issued = await cli(instance, "admin", "bridge", "issue-code", "--user-id", userEmail, "--json")
    next[`SP_${instance.toUpperCase()}_EXCHANGE_CODE`] = cardField(issued, "code")
    next[`SP_${instance.toUpperCase()}_EXCHANGE_CODE_EXPIRES`] = cardField(issued, "expires_at")
    console.log(`${instance}: exchange code ${truncate(cardField(issued, "code"))} valid until ${cardField(issued, "expires_at")}`)
  }
  await saveEnv(next)
}

// ---------------------------------------------------------------------------------------------------------------------
// capture: the browser device link of alpha, observed black box. Only HTTP traffic and rendered pages are looked at; the
// fixture keeps names, statuses and page text, never a code, PAT or JWT.

type Hit = { method: string; url: URL; headers: string[]; referer: string | null }

type Step = { section: string; method: string; url: string; status: number; location?: string; form?: string[] }

type Run = {
  instance: Instance
  api: string
  web: string
  userId: string
  scope: Scope
  hits: Hit[]
  secrets: string[]
  steps: Step[]
  section: string
  page: Page
  context: BrowserContext
}

async function capture() {
  const started = await startRun("alpha")
  const run = started.run
  console.log(`capture alpha ${run.api} (browser on ${run.web}, listener 127.0.0.1:${run.scope.port})`)
  const fixture = await observe(run).finally(started.close)

  const text = `${JSON.stringify(fixture, null, 2)}\n`
  const leaked = leaks(text, run.secrets)
  if (leaked.length > 0)
    throw new Error(`the fixture would contain ${leaked.length} secret(s) of this run; not written`)
  const file = Bun.file(fixtureFile)
  const previous: unknown = (await file.exists()) ? await file.json() : undefined
  const changes = fixtureChanges(previous, JSON.parse(text))
  await Bun.write(fixtureFile, text)
  if (previous === undefined) console.log(`fixture written: ${path.relative(repo, fixtureFile)}`)
  if (previous !== undefined && changes.length === 0) console.log("fixture unchanged: the instance answers as recorded")
  if (previous !== undefined && changes.length > 0) console.log(`fixture changed: ${changes.join(", ")}`)
  console.log("capture ok: browser device link observed end to end, PAT minted a JWT")
}

// A browser and a loopback listener against one instance, with every document and fetch request to either recorded.
async function startRun(instance: Instance): Promise<{ run: Run; close: () => Promise<unknown> }> {
  const env = await loadEnv()
  const api = url(env, instance)
  // The instance's WebAuthn relying party is `localhost` (its passkey setup links point there), so the browser uses it.
  const web = api.replace("127.0.0.1", "localhost")
  const hits: Hit[] = []
  const listener = Bun.serve({
    hostname: "127.0.0.1",
    port: 0,
    fetch(request) {
      hits.push({
        method: request.method,
        url: new URL(request.url),
        headers: [...request.headers.keys()].sort(),
        referer: request.headers.get("referer"),
      })
      return new Response("<!doctype html><title>DynWork</title><p>Signed in. You can close this window.</p>", {
        headers: { "content-type": "text/html" },
      })
    },
  })
  const browser = await launchBrowser()
  const context = await browser.newContext()
  const page = await context.newPage()
  page.setDefaultTimeout(15_000)
  const run: Run = {
    instance,
    api,
    web,
    userId: env[`SP_${instance.toUpperCase()}_USER_ID`] ?? "",
    scope: { origins: [api, web], port: listener.port ?? 0 },
    hits,
    secrets: [],
    steps: [],
    section: "",
    page,
    context,
  }
  page.on("response", (response) => {
    const request = response.request()
    const target = new URL(request.url())
    if (!["document", "fetch", "xhr"].includes(request.resourceType())) return
    if (!run.scope.origins.includes(target.origin) && target.port !== String(run.scope.port)) return
    const location = response.headers()["location"]
    const form = request.headers()["content-type"]?.includes("x-www-form-urlencoded") ? request.postData() : null
    run.steps.push({
      section: run.section,
      method: request.method(),
      url: redactUrl(request.url(), run.scope),
      status: response.status(),
      ...(location === undefined ? {} : { location: redactUrl(location, run.scope) }),
      ...(form === null ? {} : { form: [...new URLSearchParams(form).keys()] }),
    })
  })
  return { run, close: () => Promise.all([browser.close(), listener.stop(true)]) }
}

async function observe(run: Run) {
  const instance = await observeInstance(run)
  const gate = await observeLoginGate(run)
  const login = await developmentLogin(run)
  // The passkey sign-in sets no cookie, but the site gate takes the OAuth JWT as a bearer. Requests to the instance
  // origin are sent by Playwright with it and without following redirects, so the browser follows each redirect itself
  // and the loopback listener never receives the bearer.
  await run.context.route(`${run.web}/**`, async (route) =>
    route.fulfill({
      response: await route.fetch({
        headers: { ...route.request().headers(), authorization: `Bearer ${login.jwt}` },
        maxRedirects: 0,
      }),
    }),
  )
  const trip = await roundTrip(run)
  const experiments = await runExperiments(run, login.jwt)
  const revoked = await revokeCapturePats(run, trip.pat)
  return {
    captured_at: new Date().toISOString(),
    instance,
    login_gate: gate,
    development_login: login.record,
    round_trip: trip.record,
    experiments: { ...experiments, revoked_pat: revoked },
    requests: run.steps,
  }
}

