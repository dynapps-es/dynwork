// Docker and HTTP plumbing

function compose(...args: string[]) {
  return $`docker compose -p ${project} -f ${composeFile} --env-file ${envFile} ${args}`.quiet()
}

// Runs the instance's own CLI in its container; stdout is the command's result, its logs go to stderr.
async function cli(instance: Instance, ...args: string[]) {
  const result = await compose("exec", "-T", instance, "/app/bin/systemprompt", ...args).nothrow()
  if (result.exitCode !== 0) throw new Error(`${instance}: systemprompt ${args.slice(0, 3).join(" ")} failed\n${result.stderr.toString().slice(-600)}`)
  return result.stdout.toString()
}

async function sh(instance: Instance, script: string) {
  const result = await compose("exec", "-T", instance, "sh", "-c", script).nothrow()
  if (result.exitCode !== 0) throw new Error(`${instance}: ${script.split("\n")[0]} failed\n${result.stderr.toString().slice(-600)}`)
}

async function shExit(instance: Instance, script: string) {
  return (await compose("exec", "-T", instance, "sh", "-c", script).nothrow()).exitCode
}

async function waitReady(instance: Instance) {
  const base = url(await loadEnv(), instance)
  const deadline = Date.now() + 240_000
  while (Date.now() < deadline) {
    // the bridge routes mount last, so they answer only once the instance is really up
    const response = await fetch(`${base}/v1/auth/bridge/capabilities`).catch(() => undefined)
    if (response?.status === 200) return
    await Bun.sleep(1000)
  }
  throw new Error(`${instance} did not answer at ${base} within 240 s`)
}

export async function exchangePat(base: string, pat: string) {
  const response = await fetch(`${base}/v1/auth/bridge/pat`, { method: "POST", headers: { authorization: `Bearer ${pat}` } }).catch(
    () => undefined,
  )
  if (response?.status !== 200) return undefined
  const body: { token: string; ttl: number } = JSON.parse(await response.text())
  return body
}

async function missingContent(instance: Instance, base: string, pat: string) {
  const session = await exchangePat(base, pat)
  if (session === undefined) return ["a JWT"]
  const response = await fetch(`${base}/v1/bridge/manifest`, {
    headers: { authorization: `Bearer ${session.token}`, "cache-control": "no-cache" },
  })
  const envelope: { payload: string } = JSON.parse(await response.text())
  return missing(instance, JSON.parse(envelope.payload))
}

async function loadEnv(): Promise<Record<string, string>> {
  const file = Bun.file(envFile)
  return (await file.exists()) ? parseEnv(await file.text()) : {}
}

async function saveEnv(values: Record<string, string>) {
  await Bun.write(envFile, formatEnv(values))
  await $`chmod 600 ${envFile}`
}

function url(env: Record<string, string>, instance: Instance) {
  return `http://127.0.0.1:${env[`SP_${instance.toUpperCase()}_PORT`]}`
}

function requireInstance(name: string) {
  const found = instances.find((instance) => instance === name)
  if (found === undefined) throw new Error(`unknown instance "${name}", expected alpha or beta`)
  return found
}
